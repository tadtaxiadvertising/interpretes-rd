import { describe, expect, it } from 'vitest';
import { ROLEPLAY_MAX_SCENARIOS, ROLEPLAY_MULTIPART_MAX_SCENARIOS, ROLEPLAY_ADMIN_AUDIO_MAX_BYTES,
  ROLEPLAY_MULTIPART_MAX_BYTES, ROLEPLAY_STUDIO_PACKAGE_MAX_SCENARIOS, ROLEPLAY_STUDIO_PACKAGE_MAX_AUDIO_SECONDS,
  ROLEPLAY_DIRECT_UPLOAD_MAX_SLOTS, ROLEPLAY_DIRECT_UPLOAD_BATCH_MAX_BYTES } from './roleplay-limits';

describe('independent roleplay capacity budgets', () => {
  it('preserves the deployed session limit and transport bounds', () => {
    expect(ROLEPLAY_MAX_SCENARIOS).toBe(25);
    expect(ROLEPLAY_MULTIPART_MAX_SCENARIOS).toBe(25);
    expect(ROLEPLAY_ADMIN_AUDIO_MAX_BYTES).toBe(15 * 1024 * 1024);
    expect(ROLEPLAY_MULTIPART_MAX_BYTES).toBe(377 * 1024 * 1024);
    expect(ROLEPLAY_STUDIO_PACKAGE_MAX_SCENARIOS).toBe(25);
    expect(ROLEPLAY_STUDIO_PACKAGE_MAX_AUDIO_SECONDS).toBe(900);
    expect(ROLEPLAY_DIRECT_UPLOAD_MAX_SLOTS).toBe(25);
    expect(ROLEPLAY_DIRECT_UPLOAD_BATCH_MAX_BYTES).toBe(375 * 1024 * 1024);
  });
});
